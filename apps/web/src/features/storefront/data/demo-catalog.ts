function sku(id: string, label: string, price: number, inStock = true) {
  return { id, label, price, listPrice: Math.round(price * 1.12), active: true, inStock };
}

function product(
  partial: Omit<StoreProduct, 'images' | 'minPrice' | 'inStock'> & {
    images?: string[];
  },
): StoreProduct {
  const skus = partial.skus.filter((s) => s.active);
  const minPrice = skus.length ? Math.min(...skus.map((s) => s.price)) : 0;
  const inStock = skus.some((s) => s.inStock);
  return {
    ...partial,
    images: partial.images?.length ? partial.images : partial.image ? [partial.image] : [],
    minPrice,
    inStock,
  };
}

